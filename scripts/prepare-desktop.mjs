import {mkdir, copyFile, writeFile, cp, rm} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import path from 'node:path';
if (process.platform !== 'win32' || process.arch !== 'x64') throw Error('当前桌面打包脚本需要 Windows x64 Node.js。');
const root = path.resolve(import.meta.dirname, '..');
const directory = path.join(root, '.desktop-build/runtime');
const serviceDirectory = path.resolve(root, '.desktop-build/service');
if (path.dirname(serviceDirectory) !== path.join(root, '.desktop-build')) throw Error('打包暂存路径越界');
await rm(serviceDirectory, {recursive: true, force: true});
await mkdir(path.join(serviceDirectory, 'scripts'), {recursive: true});
for (const name of ['lib', 'web', 'vendor', 'tests']) await cp(path.join(root, name), path.join(serviceDirectory, name), {recursive: true});
for (const name of ['package.json', 'LICENSE', 'scripts/guard.mjs']) await copyFile(path.join(root, name), path.join(serviceDirectory, name));
await mkdir(directory, {recursive: true});
await copyFile(process.execPath, path.join(directory, 'node.exe'));
const response = await fetch(`https://raw.githubusercontent.com/nodejs/node/v${process.versions.node}/LICENSE`, {signal: AbortSignal.timeout(30000)});
if (!response.ok) throw Error('未能取得随包 Node.js 许可证：' + response.status);
await writeFile(path.join(directory, 'LICENSE.txt'), await response.text());
const result = spawnSync('powershell.exe', ['-NoProfile', '-File', path.join(root, 'scripts/create-icon.ps1')], {windowsHide: true, stdio: 'inherit'});
if (result.status !== 0) throw Error('应用图标生成失败');
console.log('已准备桌面运行时、许可证与图标。');
